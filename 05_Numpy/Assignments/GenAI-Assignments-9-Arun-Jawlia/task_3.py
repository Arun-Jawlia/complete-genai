# Important NumPy Mathematical Formulas
import numpy as np

values = np.array([2,4,6,8,10])

# Square Root
print("Square root of each element: ", np.sqrt(values))

# Exponential
print("Expontial of each element", np.exp(values))

# Natural Algo of each element
print("Natural Algo: ", np.log(values))

#Sum of all element
print("Sum of all Element: ", np.sum(values))

#Cumulative Sum of elements
print("Cumulative Sum of elements: ", np.cumsum(values))